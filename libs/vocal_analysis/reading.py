"""日本語の表記文字列からかな読みを得る。

読みを決める辞書と解析器は S2 の G2P が内部で既に持っており、利用先が同じ依存を別経路で取り込むと
読みを決める規則が2か所に分かれるため、本モジュールの公開面として出す。取り込み自体は追加依存を
要さず、追加依存が要るのは呼び出しのほう(未導入の環境でも取り込みは成立し、呼んだときに失敗する)。
"""


def to_kana_reading(text: str) -> str:
    """日本語の表記文字列(漢字かな交じり)からかな読みを返す。

    呼び出し1回につき、渡された文字列全体を1つのまとまりとして変換する(文や行へ分けて呼ぶと語の
    切れ目が変わり読みが揺れる)。変換方式は選ばせず既定の方式を使う。英語カタカナ化フォールバックも
    S2 と同じ経路をそのまま通す。読みの正しさは G2P の辞書と形態素解析に依存し、本モジュールはこれを
    補正しない。

    追加依存の未導入・モデルや辞書の取得の失敗・変換そのものの失敗は、いずれも S2 と同じ
    RecognitionError で送出する(同じ経路の同じ失敗なので分類を分けない)。
    """
    # 例外の型は追加依存を要さない側から取る(未導入の環境でも取り込みの失敗をこの型で分類できる)。
    from .phonemes import RecognitionError

    try:
        # 追加依存を要する取り込みは呼び出し時に行う(本モジュールの取り込み自体は依存を要さない)。
        from .recognizer import convert_with_g2p

        return convert_with_g2p(text, kana=True)
    except RecognitionError:
        raise
    except Exception as e:
        raise RecognitionError(
            f"かな読みへの変換に失敗しました: {type(e).__name__}: {e}") from e
