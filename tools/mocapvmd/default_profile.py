def build_default_model() -> PmxModel:
    """内蔵縮約骨格から共通 PmxModel を構築する。"""
    bones = []
    name_to_index: dict[str, int] = {}
    for i, (name, parent, position, movable, rotatable) in enumerate(_BONES):
        bones.append(
            PmxBone(
                name=name,
                name_raw=name.encode("utf-16-le"),
                english_name="",
                english_name_raw=b"",
                parent=parent,
                position=position,
                movable=movable,
                rotatable=rotatable,
                flags=0,
            )
        )
        name_to_index.setdefault(name, i)
    return PmxModel(bones=tuple(bones), name_to_index=name_to_index, warnings=())
